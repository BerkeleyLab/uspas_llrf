module marble_bsp #(
    parameter IP ={8'd192, 8'd168, 8'd19, 8'd122},
    parameter MAC = 48'h00105ad155b2,
    parameter GT_TYPE = "GT_SIM",
    parameter LB_READ_DELAY = 3,
    parameter DEFAULT_ENABLE_RX = 1,
    parameter real DSP_FREQ_MHZ = 119.0,
    parameter FCNT_WIDTH = 16  // freq_count update rate: 125M / 2**16 = 1.9kHz.
) (
    // GMII (ready for simulation with infrastructure demoed in badger/tests)
    input           gmii_tx_clk,
    output [7:0]    gmii_txd,
    output          gmii_tx_en,
    output          gmii_tx_er,
    input           gmii_rx_clk,
    input [7:0]     gmii_rxd,
    input           gmii_rx_dv,
    input           gmii_rx_er,
    output          PHY_RSTN,

    // Mailbox SPI
    input           FPGA_SCK,
    input           FPGA_CSB,
    input           FPGA_PICO,
    output          FPGA_POCI,

    // SPI boot flash programming port
    output          BOOT_CS_B,
    output          BOOT_CCLK,
    input           BOOT_MISO,
    output          BOOT_MOSI,

    // Clocks
    input           clk_locked,
    input           clk_200,
    input           dsp_clk,
    input           gt_refclk_p,
    input           gt_refclk_n,
    output          gt_rxclk,

    // lb controller
    output          m_lb_clk,
    output [23:0]   m_lb_addr,
    output          m_lb_write,
    output          m_lb_read,
    output [31:0]   m_lb_wdata,
    input  [31:0]   m_lb_rdata,
    output          m_lb_rvalid,
    output          m_lb_prefill,

    // lb peripheral, 0 - 0x3ffff
    input           lb_clk,
    input [17:0]    lb_addr,
    input           lb_write,
    input           lb_read,
    input           lb_rvalid,
    input [31:0]    lb_wdata,
    output [31:0]   lb_rdata,

    // GT related
    input           evr_gt_rxn,
    input           evr_gt_rxp,
    output [15:0]   gt_rxdata,
    output [1:0]    gt_rxcharisk,

    // diagnostics
    output          in_use,
    output [7:0]    mac_status
);

// The rw registers (GT resets, all async), their readback and the status bank
// are in marble_bsp_regs, generated by uspas_llrf/regmap.py (bsp_map()); the
// instance is with the readback below, after the status words are declared
wire [0:0] gt_soft_reset, gt_rx_slide_req;

// in lb_clk domain
wire [0:0] gt_rx_resetdone, gt_rx_aligned;
wire [31:0] gt_rx_reset_cnt;

wire [27:0] gt_rx_clk_frequency;
wire [27:0] gt_refclk_frequency;
wire gt_refclk_out;
wire gt_cplllocked;
evr_gt_wrapper #(
    .GT_TYPE(GT_TYPE)
) evr_gt_wrapper (
    .gt_refclk_p        (gt_refclk_p),
    .gt_refclk_n        (gt_refclk_n),
    .gt_rxp_in          (evr_gt_rxp),
    .gt_rxn_in          (evr_gt_rxn),

    .gt_refclk_out      (gt_refclk_out),
    .sys_clk            (lb_clk),
    .soft_reset         (gt_soft_reset),
    .rx_reset_done_sys  (gt_rx_resetdone),
    .rx_aligned_sys     (gt_rx_aligned),
    .rx_fsm_reset_cnt   (gt_rx_reset_cnt),
    .cplllocked_sys     (gt_cplllocked),

    .rx_usrclk          (gt_rxclk),
    .rxdata             (gt_rxdata),
    .rxcharisk          (gt_rxcharisk)
);

// Total miscellaneous
// See below for mac_status assignment
reg [7:0] mac_status_r=0;  always @(posedge lb_clk) mac_status_r <= mac_status;

// ---------------------
// Measure and report GT RX recovered clock
// ---------------------
freq_count #(.refcnt_width (FCNT_WIDTH)) fcnt_gt_rx_clk (
    .sysclk     (lb_clk),
    .f_in       (gt_rxclk),
    .frequency  (gt_rx_clk_frequency)
);
freq_count #(.refcnt_width (FCNT_WIDTH)) fcnt_gt_refclk (
    .sysclk     (lb_clk),
    .f_in       (gt_refclk_out),
    .frequency  (gt_refclk_frequency)
);

// Measure the phase difference between dsp_clk and evr_clk.
// Do nothing about it yet, just let people read it through localbus.
// In the LEMP system, theory says this will be quasi-static,
// just representing divider state and cable drift.
localparam PH_DIFF_DW = 13;
localparam integer  PH_DIFF_ADV = (DSP_FREQ_MHZ / 200.0 * (2**PH_DIFF_DW));
wire [13:0] ph_diff_adv_ = PH_DIFF_ADV;
wire signed [PH_DIFF_DW-1:0] evr_dsp_phsdiff;
phase_diff #(
    .dw             (PH_DIFF_DW+1)
) phase_diff_evr (
    .uclk1          (gt_rxclk),
    .uclk2          (dsp_clk),
    .uclk2g         (1'b1),
    .adv            (ph_diff_adv_),
    .sclk           (clk_200),
    .rclk           (lb_clk),
    .phdiff_out     (evr_dsp_phsdiff)
);

wire enable_rx;
wire config_s, config_p;
wire [7:0] config_a, config_d;
wire [7:0] mbox_out;
wire addrhit_mbox = lb_addr[17:12] == 6'h01; // 0x01000-0x01fff
wire lb_mbox_write = lb_write & addrhit_mbox;

mmc_mailbox #(
    .DEFAULT_ENABLE_RX(DEFAULT_ENABLE_RX)
) mailbox_i (
    .clk                (lb_clk),  // input
    // localbus mailbox memory interface
    .lb_addr            (lb_addr[10:0]), // input [10:0]
    .lb_din             (lb_wdata[7:0]), // input [7:0]
    .lb_dout            (mbox_out),      // output [7:0]
    .lb_write           (lb_mbox_write), // input
    .lb_control_strobe  (lb_read),       // input
    // SPI PHY
    .sck                (FPGA_SCK),     // input
    .ncs                (FPGA_CSB),     // input
    .pico               (FPGA_PICO),    // input
    .poci               (FPGA_POCI),    // output
    // Config pins for badger (rtefi) interface
    .config_s           (config_s),     // output
    .config_p           (config_p),     // output
    .config_a           (config_a),     // output [7:0]
    .config_d           (config_d),     // output [7:0]
    // Special pins
    .enable_rx          (enable_rx),    // output
    .spi_pins_debug     () // {MISO, din, sclk_d1, csb_d1};
);

// ---------------------
// read / write buffer, reserved for housekeeping info
// ---------------------
wire [7:0] lb_rdata_buf;
wire lb_buf_wen = lb_write & (lb_addr[17:12]==3);     // 0x3000 - 0x3fff, 4k bytes
dpram #(
    .dw(8),
    .aw(12)
) dpram_buf (
    .clka   (lb_clk),
    .addra  (lb_addr[11:0]),
    .dina   (lb_wdata[7:0]),
    .wena   (lb_buf_wen),
    .clkb   (lb_clk),
    .addrb  (lb_addr[11:0]),
    .doutb  (lb_rdata_buf)
);

// ---------------------
// Register file and readback, generated: rw registers with their mirror, the
// status bank (offset 0x2000) and the readback mux over the windows. The
// mailbox (0x1000) is read through the unregistered bypass below, so its
// window data are tied low here.
// ---------------------
wire [31:0] lb_rdata_r;
marble_bsp_regs regs (
    .lb_clk                 (lb_clk),
    .lb_addr                (lb_addr),
    .lb_write               (lb_write),
    .lb_read                (lb_read),
    .lb_wdata               (lb_wdata),
    .lb_rdata               (lb_rdata_r),
    .gt_soft_reset          (gt_soft_reset),
    .gt_rx_slide_req        (gt_rx_slide_req),
    .mac_status_r           (mac_status_r),
    .gt_rx_clk_frequency    (gt_rx_clk_frequency),
    .gt_refclk_frequency    (gt_refclk_frequency),
    .gt_rx_resetdone        (gt_rx_resetdone),
    .gt_rx_aligned          ({31'b0, gt_rx_aligned}),
    .evr_dsp_phsdiff        (evr_dsp_phsdiff),
    .gt_rx_reset_cnt        (gt_rx_reset_cnt),
    .rd_marble_mbox_buf     (32'h0),
    .rd_bsp_info_buf        ({24'h0, lb_rdata_buf})
);

// The mailbox readout from fake_dpram can't be registered again
assign lb_rdata = addrhit_mbox ? {24'h000000, mbox_out} : lb_rdata_r;

// Keep the PHY's reset pin low for the first 33 ms
reg [26:0] rx_heartbeat=0, tx_heartbeat=0;
always @(posedge gmii_rx_clk) rx_heartbeat <= rx_heartbeat+1;
always @(posedge gmii_tx_clk) tx_heartbeat <= tx_heartbeat+1;
reg phy_rb=0;
always @(posedge gmii_tx_clk) begin
    if (tx_heartbeat[21]) phy_rb <= 1;
    if (~clk_locked) phy_rb <= 0;
end
assign PHY_RSTN = phy_rb;

// localbus master
wire rx_mon;
wire tx_mon;
wire blob_in_use, boot_busy;
rtefi_blob #(
    .ip(IP), .mac(MAC), .p3_read_pipe_len(LB_READ_DELAY)
) ether_gmii_i (
    .tx_clk         (gmii_tx_clk),
    .rx_clk         (gmii_rx_clk),
    .rxd            (gmii_rxd),
    .rx_dv          (gmii_rx_dv),
    .rx_er          (gmii_rx_er),
    .txd            (gmii_txd),
    .tx_en          (gmii_tx_en),
    .tx_er          (gmii_tx_er),

    .enable_rx      (enable_rx),
    .config_clk     (gmii_tx_clk),
    .config_a       (config_a[3:0]),  // input [3:0]
    .config_d       (config_d),  // input [7:0]
    .config_s       (config_s),  // MAC/IP address write
    .config_p       (config_p),  // UDP port number write
    .p2_nomangle    (1'h0),

    .host_raddr     (),
    .host_rdata     (16'h0),
    .buf_start_addr (10'h0),
    .tx_mac_start   (1'b0),
    .rx_mac_hbank   (1'b0),
    .rx_mac_accept  (1'b0),
    .tx_mac_done    (),

    .p3_lb_clk      (m_lb_clk),
    .p3_lb_addr     (m_lb_addr),
    .p3_lb_write    (m_lb_write),
    .p3_lb_read     (m_lb_read),
    .p3_lb_rvalid   (m_lb_rvalid),
    .p3_lb_wdata    (m_lb_wdata),
    .p3_lb_rdata    (m_lb_rdata),
    .p3_lb_prefill  (m_lb_prefill),
    .rx_mon         (rx_mon),
    .tx_mon         (tx_mon),

    .p4_spi_clk     (BOOT_CCLK),
    .p4_spi_cs      (BOOT_CS_B),
    .p4_spi_mosi    (BOOT_MOSI),
    .p4_spi_miso    (BOOT_MISO),
    .p4_busy        (boot_busy),
    .in_use         (blob_in_use)
);

assign in_use = blob_in_use | boot_busy;

// Not in a single clock domain, but keep it that way for
// all-else-fails level debugging, e.g., sending to LEDs on a Pmod.
// See above for code that captures it for localbus monitoring.
assign mac_status = {4'h0, tx_heartbeat[26], rx_heartbeat[26], tx_mon, rx_mon};

endmodule
