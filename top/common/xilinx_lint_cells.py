#!/usr/bin/env python3
"""Xilinx primitives for the board-level lint (make lint in top/<design>/).

Yosys's cells_xtra.v declares each primitive as a black box with its
parameters and ports, but in Yosys's own shorthand, `module NAME (...);`,
which Verilator does not read. This writes the same modules with explicit port
lists. Vivado's unisim models are not an option: Verilator cannot elaborate
them (signal strengths, tristates, references to glbl).
"""
import argparse
import re

PORT = re.compile(r'^\s*(input|output|inout)\b[^;]*?(\w+)\s*;')


def explicit_ports(text):
    out = []
    module = None
    for line in text.splitlines():
        m = re.match(r'^module\s+(\w+)\s*\(\.\.\.\);', line)
        if m:
            module = (m.group(1), [], [])
            continue
        if module is None:
            out.append(line)
            continue
        name, ports, body = module
        p = PORT.match(line)
        if p:
            ports.append(p.group(2))
        body.append(line)
        if re.match(r'^endmodule\b', line):
            out.append(f"module {name} ({', '.join(ports)});")
            out.extend(body)
            module = None
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('cells_xtra', help="Yosys's share/yosys/xilinx/cells_xtra.v")
    ap.add_argument('-o', '--output', required=True)
    args = ap.parse_args()
    with open(args.cells_xtra) as f:
        text = f.read()
    with open(args.output, 'w') as f:
        f.write(f"// Generated by xilinx_lint_cells.py from {args.cells_xtra}\n")
        f.write(explicit_ports(text))


if __name__ == '__main__':
    main()
